import AppKit
import DevBarCore
import Synchronization
import Testing

@testable import DevBar

private final class FakePasteboardReader: PasteboardReading, Sendable {
  struct State {
    var count = 1
    var types = ["public.utf8-plain-text"]
    var access: PasteboardMetadata.Access = .allow
    var reads = 0
    var delay = false
    var changeDuringRead = false
    var payloads = [ClipboardPayload(type: "public.utf8-plain-text", data: Data("test".utf8))]
  }
  let state = Mutex(State())
  func metadata() -> PasteboardMetadata {
    state.withLock { PasteboardMetadata(count: $0.count, types: $0.types, access: $0.access) }
  }
  func read() -> [ClipboardPayload] {
    let delay = state.withLock {
      $0.reads += 1
      return $0.delay
    }
    if delay { Thread.sleep(forTimeInterval: 0.1) }
    return state.withLock {
      if $0.changeDuringRead { $0.count += 1 }
      return $0.payloads
    }
  }
}

@MainActor @Test func clipboardMonitorReadsOnceAndIgnoresOwnWrite() async {
  let reader = FakePasteboardReader()
  let monitor = ClipboardMonitor(reader: reader)
  var captures = 0
  monitor.onCapture = { _, _ in captures += 1 }
  await monitor.poll()
  await monitor.poll()
  #expect(captures == 1)
  reader.state.withLock { $0.count = 2 }
  monitor.markSelfWrite(2)
  await monitor.poll()
  #expect(reader.state.withLock { $0.reads } == 1)
}

@MainActor
@Test(arguments: [
  "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
])
func clipboardMonitorFiltersPrivacyBeforeContent(type: String) async {
  let reader = FakePasteboardReader()
  reader.state.withLock {
    $0.types.append(type)
    $0.access = .ask
  }
  let monitor = ClipboardMonitor(reader: reader)
  await monitor.poll(userInitiated: true)
  #expect(reader.state.withLock { $0.reads } == 0)
  #expect(!monitor.pending)
}

@MainActor @Test(arguments: [PasteboardMetadata.Access.ask, .deny])
func clipboardMonitorNeverReadsWithoutAutomaticPermission(access: PasteboardMetadata.Access) async {
  let reader = FakePasteboardReader()
  reader.state.withLock { $0.access = access }
  let monitor = ClipboardMonitor(reader: reader)
  await monitor.poll()
  #expect(reader.state.withLock { $0.reads } == 0)
  #expect(monitor.pending == (access == .ask))
  reader.state.withLock { $0.access = .allow }
  await monitor.poll()
  // Denied copies are deliberately not pending; allow the next copy to resume.
  if access == .deny {
    reader.state.withLock { $0.count += 1 }
    await monitor.poll()
  }
  #expect(reader.state.withLock { $0.reads } == 1)
}

@MainActor @Test func clipboardMonitorDiscardsChangedClipboardAndDoesNotTreatNilAsDenied() async {
  let reader = FakePasteboardReader()
  reader.state.withLock { $0.changeDuringRead = true }
  let monitor = ClipboardMonitor(reader: reader)
  var captures = 0
  monitor.onCapture = { _, _ in captures += 1 }
  await monitor.poll()
  #expect(captures == 0)
  reader.state.withLock {
    $0.changeDuringRead = false
    $0.payloads = []
    $0.count += 1
  }
  await monitor.poll()
  #expect(captures == 0)
  #expect(monitor.access == .allow)
}

@MainActor @Test func clipboardExplicitBlockingReadDoesNotBlockMainActor() async {
  let reader = FakePasteboardReader()
  reader.state.withLock {
    $0.access = .ask
    $0.delay = true
  }
  let monitor = ClipboardMonitor(reader: reader)
  let task = Task { await monitor.poll(userInitiated: true) }
  for _ in 0..<100 {
    if reader.state.withLock({ $0.reads }) > 0 { break }
    try? await Task.sleep(for: .milliseconds(1))
  }
  #expect(monitor.waiting)
  let start = ContinuousClock.now
  await Task.yield()
  #expect(start.duration(to: .now) < .milliseconds(50))
  await task.value
  #expect(!monitor.waiting)
}
